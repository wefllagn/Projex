import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { createMemoryRouter, RouterProvider } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { ClassContext } from '../classes/class-context.js'
import { ApiError } from '../api/api-client.js'
import GroupBrowserEditor from './GroupBrowserEditor.jsx'

const welcomeKey = 'projex.group-editor.hide-welcome'
beforeEach(()=>localStorage.setItem(welcomeKey,'yes'))

const hash = 'a'.repeat(40), second = 'b'.repeat(40)
const permissionKeys = ['canRead','canWrite','canUpdateMain','canManageMembers','canInviteMembers','canReview','canRequestChanges','canSubmitForReview','canViewActivity','canEditFeedback','canArchive','canRestore']
function setup({ permissions = {}, branches = [], commits: commitOverrides = {}, git: gitOverrides = {}, refsApi } = {}) {
  const context = { repositoryId:'repo', project:{id:'project',title:'Project task',status:'PUBLISHED',dueDate:'2099-01-01T00:00:00Z'}, class:{id:'class',className:'Class',status:'ACTIVE'}, team:{id:'team',name:'Group',status:'ACTIVE',activeMemberCount:2}, teachingStaff:[], currentRole:'MAINTAINER', permissions:{...Object.fromEntries(permissionKeys.map(key=>[key,false])),canRead:true,canWrite:true,canUpdateMain:true,...permissions} }
  const api = { getRepository:vi.fn().mockResolvedValue({data:{id:'repo',projectTaskId:'project',repositoryName:'Actual repository'}}), getGroupContext:vi.fn().mockResolvedValue({data:context}) }
  const getTree = vi.fn((_id,query)=>Promise.resolve({data:{commitId:query.commitId,path:query.path||'',entries:[{name:'README.md',path:'README.md',entryType:'blob',objectId:second,sizeBytes:8}]}}))
  const gitApi = {listBranches:vi.fn().mockResolvedValue({data:branches}),getTree,getFile:vi.fn((_id,query)=>Promise.resolve({data:{commitId:query.commitId,path:query.path,content:'Original',encoding:'utf-8',sizeBytes:8}})),...gitOverrides}
  const pending={jobId:'job',repositoryId:'repo',filePath:'README.md',branchName:'main',status:'PENDING',commitHash:null}
  const commits={create:vi.fn().mockResolvedValue({data:pending}),get:vi.fn().mockResolvedValue({data:{...pending,status:'SUCCEEDED',commitHash:second}}),...commitOverrides}
  const router=createMemoryRouter([{path:'/student/projects/:projectTaskId/repositories/:repositoryId/editor',element:<GroupBrowserEditor api={api} gitApi={gitApi} commits={commits} refsApi={refsApi} pollingOptions={{initialDelayMs:1,maximumDelayMs:1,maximumDurationMs:200}} />}],{initialEntries:['/student/projects/project/repositories/repo/editor?classId=class&branch=main']})
  const view = render(<ClassContext.Provider value={{selectedClass:{id:'class'}}}><RouterProvider router={router} /></ClassContext.Provider>)
  return {api,gitApi,commits,context,pending,...view}
}
describe('Group browser editor',()=>{
  it('commits only after an intentional message/action, then shows the actual result and refreshed files',async()=>{
    const {commits,gitApi}=setup()
    const source=await screen.findByRole('textbox',{name:'Group file source'})
    expect(screen.getByRole('heading',{name:'Actual repository'})).toBeInTheDocument()
    expect(commits.create).not.toHaveBeenCalled()
    fireEvent.change(source,{target:{value:'# Browser README\n'}})
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Initialize README'}})
    expect(commits.create).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button',{name:'Commit Changes'}))
    expect(await screen.findByText(/Committed bbbbbbbb/)).toBeInTheDocument()
    expect(commits.create).toHaveBeenCalledExactlyOnceWith('repo',expect.objectContaining({branchName:'main',filePath:'README.md',content:'# Browser README\n',operation:'CREATE',expectedHeadCommitHash:null,commitMessage:'Initialize README'}),expect.stringMatching(/^group:/))
    expect(await screen.findByRole('button',{name:'README.md'})).toBeInTheDocument()
    expect(gitApi.getTree).toHaveBeenCalledWith('repo',{commitId:second})
    expect(screen.queryByRole('button',{name:'Submit'})).not.toBeInTheDocument()
    expect(screen.queryByRole('button',{name:/Run Tests|Compile/})).not.toBeInTheDocument()
  })
  it('does not let an ordinary Developer initialize protected main',async()=>{
    const {commits}=setup({permissions:{canUpdateMain:false}})
    expect(await screen.findByText(/Main is protected/)).toBeInTheDocument()
    expect(screen.getByRole('button',{name:'Commit Changes'})).toBeDisabled()
    expect(screen.queryByRole('button',{name:'Create file'})).not.toBeInTheDocument()
    expect(commits.create).not.toHaveBeenCalled()
  })
  it('requires deliberate discard before replacing an unsaved file',async()=>{
    setup();await screen.findByLabelText('Group file source')
    fireEvent.click(screen.getByRole('button',{name:'New file',exact:true}))
    fireEvent.change(screen.getByLabelText('New file path'),{target:{value:'src/Main.java'}})
    fireEvent.click(screen.getByRole('button',{name:'Create file'}))
    expect(await screen.findByRole('dialog',{name:'Discard changes?'})).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button',{name:'Cancel'}))
    expect(screen.getByLabelText('Group file source')).toHaveValue('# Project task\n')
    expect(screen.getAllByText('README.md').length).toBeGreaterThan(0)
  })
  it('keeps source after a failed job and does not report a fabricated commit',async()=>{
    const pending={jobId:'job',repositoryId:'repo',filePath:'README.md',branchName:'main',status:'FAILED',commitHash:null}
    setup({commits:{get:vi.fn().mockResolvedValue({data:pending})}})
    const source=await screen.findByLabelText('Group file source')
    fireEvent.change(source,{target:{value:'Keep these edits'}});fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Save changes'}})
    fireEvent.click(screen.getByRole('button',{name:'Commit Changes'}))
    expect(await screen.findByText(/The commit was not applied/)).toBeInTheDocument()
    expect(source).toHaveValue('Keep these edits');expect(screen.queryByText(/Committed /)).not.toBeInTheDocument()
  })
  it('keeps an ambiguous request frozen and retries the identical payload and key',async()=>{
    const create=vi.fn().mockRejectedValueOnce(new ApiError({code:'NETWORK_ERROR',message:'offline'})).mockResolvedValue({data:{jobId:'job',repositoryId:'repo',filePath:'README.md',branchName:'main',status:'PENDING',commitHash:null}})
    setup({commits:{create}})
    const source=await screen.findByLabelText('Group file source')
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Initial commit'}});fireEvent.click(screen.getByRole('button',{name:'Commit Changes'}))
    fireEvent.click(await screen.findByRole('button',{name:'Retry same commit request'}))
    await screen.findByText(/Committed bbbbbbbb/)
    expect(create).toHaveBeenCalledTimes(2);expect(create.mock.calls[1]).toEqual(create.mock.calls[0]);expect(source).toHaveValue('# Project task\n')
  })
  it('preserves edits on a stale branch until the Student reviews and explicitly adopts a newer base',async()=>{
    const branches=[{branchName:'main',isDefault:true,commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]
    const {gitApi,commits,pending}=setup({branches})
    fireEvent.click(await screen.findByRole('button',{name:'README.md'}))
    const source=await screen.findByLabelText('Group file source');fireEvent.change(source,{target:{value:'My edits'}})
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Update README'}})
    commits.get.mockResolvedValue({data:{...pending,status:'CONFLICTED',failureCode:'BROWSER_HEAD_CHANGED'}})
    fireEvent.click(screen.getByRole('button',{name:'Commit Changes'}))
    expect(await screen.findByRole('button',{name:'Compare latest'})).toBeInTheDocument();expect(source).toHaveValue('My edits')
    expect(screen.getByRole('button',{name:'Commit Changes'})).toBeDisabled()
    gitApi.listBranches.mockResolvedValue({data:[{...branches[0],commitId:second}]})
    fireEvent.click(screen.getByRole('button',{name:'Compare latest'}))
    fireEvent.click(await screen.findByRole('button',{name:'Keep edits on latest base'}))
    fireEvent.click(await screen.findByRole('button',{name:'Confirm'}))
    expect(source).toHaveValue('My edits')
    await waitFor(()=>expect(screen.getByRole('button',{name:'Commit Changes'})).toBeEnabled())
    expect(commits.create).toHaveBeenCalledTimes(1)
  })
  it('shows the guide again on editor entry unless the user explicitly opts out',async()=>{
    localStorage.removeItem(welcomeKey)
    sessionStorage.setItem('projex.group-editor.welcome.dismissed','yes')
    const first=setup()
    const dialog=await screen.findByRole('dialog',{name:'Code in Origin'})
    expect(dialog).toHaveTextContent('For advanced development and Git features, we recommend cloning this repository and using your preferred IDE.')
    expect(dialog).toHaveTextContent('question-mark help button')
    expect(screen.getByRole('checkbox',{name:'Do not show this again'})).not.toBeChecked()
    expect(screen.queryByText('Prefer your own IDE?')).not.toBeInTheDocument()
    expect(screen.getByRole('link',{name:'View clone options'})).toHaveAttribute('href',expect.stringContaining('tab=code&branch=main'))
    fireEvent.click(screen.getByRole('button',{name:'I understand'}))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.queryByText(/For advanced development/)).not.toBeInTheDocument()
    expect(localStorage.getItem(welcomeKey)).toBeNull()
    expect(first.commits.create).not.toHaveBeenCalled()
    first.unmount()
    const second=setup()
    expect(await screen.findByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
    expect(second.commits.create).not.toHaveBeenCalled()
  })
  it('remembers an explicit opt-out, always permits help, and can restore automatic welcomes',async()=>{
    localStorage.removeItem(welcomeKey)
    const first=setup()
    fireEvent.click(await screen.findByRole('checkbox',{name:'Do not show this again'}))
    fireEvent.click(screen.getByRole('button',{name:'I understand'}))
    expect(localStorage.getItem(welcomeKey)).toBe('yes')
    first.unmount()
    const second=setup()
    await screen.findByLabelText('Group file source')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    const help=screen.getByRole('button',{name:'Editor help',exact:true})
    expect(help).toHaveTextContent('')
    expect(help.querySelector('svg')).toHaveAttribute('aria-hidden','true')
    help.focus()
    fireEvent.click(help)
    expect(screen.getByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
    expect(screen.getByRole('checkbox',{name:'Do not show this again'})).toBeChecked()
    fireEvent.click(screen.getByRole('checkbox',{name:'Do not show this again'}))
    fireEvent.click(screen.getByRole('button',{name:'I understand'}))
    expect(help).toHaveFocus()
    expect(localStorage.getItem(welcomeKey)).toBeNull()
    expect(second.commits.create).not.toHaveBeenCalled()
    second.unmount()
    setup()
    expect(await screen.findByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
  })
  it.each(['close','escape'])('does not treat %s dismissal as an opt-out',async method=>{
    localStorage.removeItem(welcomeKey)
    const first=setup()
    const dialog=await screen.findByRole('dialog',{name:'Code in Origin'})
    if (method === 'close') fireEvent.click(screen.getByRole('button',{name:'Close Code in Origin'}))
    else fireEvent.keyDown(dialog,{key:'Escape'})
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(localStorage.getItem(welcomeKey)).toBeNull()
    first.unmount()
    setup()
    expect(await screen.findByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
  })
  it('still opens and dismisses help when browser preference storage is unavailable',async()=>{
    const get=vi.spyOn(Storage.prototype,'getItem').mockImplementation(()=>{throw new Error('Storage unavailable')})
    const set=vi.spyOn(Storage.prototype,'setItem').mockImplementation(()=>{throw new Error('Storage unavailable')})
    try {
      const {commits}=setup()
      expect(await screen.findByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
      fireEvent.click(screen.getByRole('checkbox',{name:'Do not show this again'}))
      fireEvent.click(screen.getByRole('button',{name:'I understand'}))
      expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
      fireEvent.click(screen.getByRole('button',{name:'Editor help'}))
      expect(screen.getByRole('dialog',{name:'Code in Origin'})).toBeInTheDocument()
      expect(commits.create).not.toHaveBeenCalled()
    } finally { get.mockRestore(); set.mockRestore() }
  })
  it('opens an existing README as an editable file rather than creating another one',async()=>{
    setup({branches:[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]})
    expect(await screen.findByLabelText('Group file source')).toHaveValue('Original')
    expect(screen.queryByLabelText('New file path')).not.toBeInTheDocument()
    expect(screen.getByText('Saved snapshot')).toBeInTheDocument()
  })
  it('prevents duplicate file creation and offers to open the existing file',async()=>{
    const {commits}=setup({branches:[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]})
    await screen.findByLabelText('Group file source')
    fireEvent.click(screen.getByRole('button',{name:'New file',exact:true}))
    fireEvent.change(screen.getByLabelText('New file path'),{target:{value:'README.md'}})
    fireEvent.click(screen.getByRole('button',{name:'Create file',exact:true}))
    expect(await screen.findByText('This file already exists. Open it to edit its contents.')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button',{name:'Open existing file'}))
    await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.getByLabelText('Group file source')).toHaveValue('Original')
    expect(commits.create).not.toHaveBeenCalled()
  })
  it('creates only a local draft after an authoritative missing-file result',async()=>{
    const {gitApi,commits}=setup({branches:[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]})
    await screen.findByLabelText('Group file source')
    gitApi.getFile.mockRejectedValueOnce(new ApiError({status:404,code:'GIT_CONTENT_NOT_FOUND'}))
    fireEvent.click(screen.getByRole('button',{name:'New file',exact:true}))
    fireEvent.change(screen.getByLabelText('New file path'),{target:{value:'src/Main.java'}})
    fireEvent.click(screen.getByRole('button',{name:'Create file',exact:true}))
    await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.getByLabelText('Group file source')).toHaveValue('')
    expect(screen.getByText('Unsaved changes')).toBeInTheDocument()
    expect(commits.create).not.toHaveBeenCalled()
  })
  it('keeps the new-file dialog and draft when filename checking fails',async()=>{
    const {gitApi}=setup({branches:[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]})
    await screen.findByLabelText('Group file source')
    gitApi.getFile.mockRejectedValueOnce(new ApiError({status:503,code:'GIT_INSPECTION_FAILED'}))
    fireEvent.click(screen.getByRole('button',{name:'New file',exact:true}))
    fireEvent.change(screen.getByLabelText('New file path'),{target:{value:'src/Main.java'}})
    fireEvent.click(screen.getByRole('button',{name:'Create file',exact:true}))
    expect(await screen.findByText('We could not check this filename. Try again before creating it.')).toBeInTheDocument()
    expect(screen.getByLabelText('New file path')).toHaveValue('src/Main.java')
    expect(screen.getByLabelText('Group file source')).toHaveValue('Original')
  })
  it('turns a server-side file collision into explicit comparison while preserving the draft',async()=>{
    const {commits,pending}=setup()
    const source=await screen.findByLabelText('Group file source')
    fireEvent.change(source,{target:{value:'Keep my code'}})
    commits.get.mockResolvedValue({data:{...pending,status:'FAILED',failureCode:'BROWSER_FILE_CHANGED'}})
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Save README'}})
    fireEvent.click(screen.getByRole('button',{name:'Commit Changes'}))
    expect(await screen.findByRole('button',{name:'Compare latest'})).toBeInTheDocument()
    expect(source).toHaveValue('Keep my code')
    expect(screen.getByRole('button',{name:'Commit Changes'})).toBeDisabled()
    expect(screen.queryByText(/check your permissions/i)).not.toBeInTheDocument()
  })

  it('does not let a large README block opening other supported files',async()=>{
    const getTree=vi.fn((_id,query)=>Promise.resolve({data:{commitId:query.commitId,path:'',entries:[{name:'README.md',path:'README.md',entryType:'blob',objectId:second,sizeBytes:70000},{name:'Main.java',path:'Main.java',entryType:'blob',objectId:second,sizeBytes:8}]}}))
    const {gitApi}=setup({branches:[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}],git:{getTree}})
    expect(await screen.findByLabelText('Group file source')).toHaveValue('Original')
    expect(gitApi.getFile).toHaveBeenCalledWith('repo',{commitId:hash,path:'Main.java'})
    expect(screen.getByRole('button',{name:'README.md'})).toBeInTheDocument()
  })


  it('creates and switches branches without committing or discarding the current source/message, including Enter submission',async()=>{
    const branches=[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'}]
    const refsApi={create:vi.fn((_id,input)=>Promise.resolve({data:{jobId:'ref',repositoryId:'repo',...input,status:'SUCCEEDED',commitHash:hash}})),get:vi.fn(),preview:vi.fn()}
    const {commits}=setup({branches,refsApi})
    const source=await screen.findByLabelText('Group file source')
    fireEvent.change(source,{target:{value:'Keep this unsaved source'}})
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Keep this message'}})
    fireEvent.click(screen.getByRole('button',{name:'New Branch',exact:true}))
    fireEvent.change(screen.getByLabelText('New branch name'),{target:{value:'feature/new'}})
    fireEvent.submit(screen.getByLabelText('New branch name').closest('form'))
    await waitFor(()=>expect(screen.getByLabelText('Editor branch')).toHaveValue('feature/new'))
    expect(source).toHaveValue('Keep this unsaved source')
    expect(screen.getByLabelText('Commit message')).toHaveValue('Keep this message')
    expect(commits.create).not.toHaveBeenCalled()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('retains a dirty target draft after merge and requires comparison before another commit',async()=>{
    const branches=[{branchName:'main',commitId:hash,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Initial'},{branchName:'feature/new',commitId:second,authorName:'Student',authoredAt:'2026-10-23T00:00:00Z',subject:'Feature'}]
    const refsApi={create:vi.fn((_id,input)=>Promise.resolve({data:{jobId:'ref',repositoryId:'repo',...input,status:'SUCCEEDED',commitHash:second}})),get:vi.fn(),preview:vi.fn().mockResolvedValue({data:{repositoryId:'repo',sourceBranchName:'feature/new',targetBranchName:'main',sourceCommitHash:second,targetCommitHash:hash,fastForward:true,upToDate:false,commitCount:1,files:['README.md'],commits:[{commitId:second,subject:'Feature'}]}})}
    const {commits}=setup({branches,refsApi})
    const source=await screen.findByLabelText('Group file source')
    fireEvent.change(source,{target:{value:'Keep my main draft'}})
    fireEvent.change(screen.getByLabelText('Commit message'),{target:{value:'Keep my message'}})
    fireEvent.click(screen.getByRole('button',{name:'Merge Branch',exact:true}));fireEvent.click(screen.getByRole('button',{name:'Review merge'}))
    fireEvent.click(await screen.findByRole('button',{name:'Confirm merge'}))
    expect(await screen.findByRole('button',{name:'Compare latest'})).toBeInTheDocument()
    expect(source).toHaveValue('Keep my main draft')
    expect(screen.getByLabelText('Commit message')).toHaveValue('Keep my message')
    expect(screen.getByRole('button',{name:'Commit Changes'})).toBeDisabled()
    expect(commits.create).not.toHaveBeenCalled()
  })
})
