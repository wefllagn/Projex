import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { AuthContext } from '../auth/auth-context.js'
import { RepositoryCodeMenu } from './RepositoryCodeMenu.jsx'
import { ApiError } from '../api/api-client.js'
const repository = { id: 'repo', defaultBranch: 'main' }
const credential = { credentialId: 'access', repositoryId: 'repo', operations: ['READ', 'WRITE'], createdAt: '2026-01-01T00:00:00Z', expiresAt: '2099-01-01T00:00:00Z', revokedAt: null, username: 'returned-git-user', secret: 'synthetic-secret' }
function api(write = true) { return { getAccess: vi.fn().mockResolvedValue({ data: { id: repository.id, gitPermissions: { read: true, write, canUpdateMain: false } } }), getTransportUrl: vi.fn().mockReturnValue('http://localhost:5197/api/v1/git/repositories/repo'), issueCredential: vi.fn((_id, operations) => Promise.resolve({ data: { ...credential, operations } })), listCredentials: vi.fn().mockResolvedValue({ data: [credential] }), revokeCredential: vi.fn().mockResolvedValue({ data: { ...credential, revokedAt: '2026-10-22T00:00:00Z' } }) } }
async function openAccess() {
  fireEvent.click(screen.getByRole('button', { name: 'Code' }))
  fireEvent.click(screen.getByRole('button', { name: 'Get Git access' }))
  await act(async () => {})
}
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })
describe('simplified shared Git access', () => {
  it('keeps Code compact and copies the exact URL without requesting credentials or metadata', async () => {
    const gitApi = api(), copy = vi.fn().mockResolvedValue()
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: copy } })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    fireEvent.click(screen.getByRole('button', { name: 'Code' }))
    expect(screen.getByRole('button', { name: 'Get Git access' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'How to use Git' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Generate write access' })).not.toBeInTheDocument()
    expect(screen.queryByText('Git commands')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Copy URL' }))
    await waitFor(() => expect(copy).toHaveBeenCalledExactlyOnceWith(gitApi.getTransportUrl.mock.results[0].value))
    expect(screen.getByRole('status')).toHaveTextContent('Copied!')
    expect(gitApi.issueCredential).not.toHaveBeenCalled()
    expect(gitApi.listCredentials).not.toHaveBeenCalled()
  })
  it.each([false, true])('selects authoritative scope with one deliberate action write=%s and copies actual returned fields', async (write) => {
    const gitApi = api(write), copy = vi.fn().mockResolvedValue()
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: copy } })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    expect(screen.getAllByRole('dialog')).toHaveLength(1)
    expect(screen.getByRole('dialog', { name: 'Git access', exact: true })).toHaveAttribute('aria-modal', 'true')
    expect(gitApi.issueCredential).not.toHaveBeenCalled()
    expect(gitApi.listCredentials).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByText('synthetic-secret')
    expect(gitApi.issueCredential).toHaveBeenCalledExactlyOnceWith('repo', write ? ['READ', 'WRITE'] : ['READ'])
    fireEvent.click(screen.getByRole('button', { name: 'Copy username' }))
    await waitFor(() => expect(copy).toHaveBeenLastCalledWith('returned-git-user'))
    fireEvent.click(screen.getByRole('button', { name: 'Copy token' }))
    await waitFor(() => expect(copy).toHaveBeenLastCalledWith('synthetic-secret'))
    expect(screen.getByRole('status')).not.toHaveTextContent('synthetic-secret')
    expect(gitApi.getTransportUrl.mock.results[0].value).not.toContain('synthetic-secret')
    fireEvent.click(screen.getByRole('button', { name: 'Close Git access' }))
    expect(screen.queryByText('synthetic-secret')).not.toBeInTheDocument()
    await waitFor(() => expect(screen.getByRole('button', { name: 'Code' })).toHaveFocus())
    expect(localStorage.length).toBe(0); expect(sessionStorage.length).toBe(0)
  })
  it('uses one modal for management, confirmation, result and options, updating only from server response', async () => {
    const gitApi = api()
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Manage access' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Revoke', exact: true }))
    expect(screen.getAllByRole('dialog')).toHaveLength(1)
    expect(gitApi.revokeCredential).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel', exact: true }))
    expect(gitApi.revokeCredential).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Revoke', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Revoke access', exact: true }))
    expect(await screen.findByText('Access revoked.')).toBeInTheDocument()
    expect(gitApi.revokeCredential).toHaveBeenCalledExactlyOnceWith('access')
    expect(screen.queryByRole('button', { name: 'Revoke', exact: true })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'History (1)' })).toHaveAttribute('aria-expanded', 'false')
  })
  it('keeps numerous historical records collapsed and renders only one short page at a time', async () => {
    const gitApi = api()
    gitApi.listCredentials.mockResolvedValue({ data: [credential, ...Array.from({ length: 83 }, (_, index) => ({ ...credential, credentialId: `historical-${index}`, revokedAt: index % 2 ? null : '2026-01-02T00:00:00Z', expiresAt: '2026-01-03T00:00:00Z' }))] })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available />)
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Manage access' }))
    const history = await screen.findByRole('button', { name: 'History (83)' })
    expect(history).toHaveAttribute('aria-expanded', 'false')
    expect(screen.getAllByRole('listitem')).toHaveLength(1)
    expect(screen.queryByText('Credential ID')).not.toBeInTheDocument()
    fireEvent.click(history)
    expect(screen.getAllByRole('listitem')).toHaveLength(7)
    fireEvent.click(within(screen.getByRole('navigation', { name: 'Credential history pages' })).getByRole('button', { name: 'Next' }))
    expect(screen.getAllByRole('listitem')).toHaveLength(7)
    expect(screen.getByRole('navigation', { name: 'Credential history pages' })).toHaveTextContent('2 of 14')
  })
  it('preserves active metadata and offers explicit retry after a failed revocation', async () => {
    const gitApi = api()
    gitApi.revokeCredential.mockRejectedValueOnce(new ApiError({ status: 503, message: 'PRIVATE DETAIL' })).mockResolvedValue({ data: { ...credential, revokedAt: '2026-10-22T00:00:00Z' } })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available />)
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Manage access' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Revoke', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Revoke access', exact: true }))
    await screen.findByRole('alert')
    expect(screen.queryByText('PRIVATE DETAIL')).not.toBeInTheDocument()
    expect(gitApi.revokeCredential).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('button', { name: 'Revoke access' })).toBeEnabled()
    fireEvent.click(screen.getByRole('button', { name: 'Revoke access' }))
    expect(await screen.findByText('Access revoked.')).toBeInTheDocument()
  })
  it('hides unauthorized write controls and never automatically retries a failed generation', async () => {
    const gitApi = api(false)
    gitApi.issueCredential.mockRejectedValue(new ApiError({ status: 503, message: 'PRIVATE DETAIL' }))
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available />)
    await openAccess()
    expect(screen.queryByRole('button', { name: 'Generate write access' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByRole('alert')
    expect(gitApi.issueCredential).toHaveBeenCalledExactlyOnceWith('repo', ['READ'])
    expect(screen.queryByText('PRIVATE DETAIL')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Generate credentials' })).toBeEnabled()
  })
  it('clears expired secrets and requires a deliberate new generation', async () => {
    vi.useFakeTimers()
    const gitApi = api()
    gitApi.issueCredential.mockResolvedValue({ data: { ...credential, expiresAt: new Date(Date.now() + 1000).toISOString() } })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' })))
    expect(screen.getByText('synthetic-secret')).toBeInTheDocument()
    await act(async () => vi.advanceTimersByTimeAsync(1001))
    expect(screen.queryByText('synthetic-secret')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Access token expired' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Get new access' }))
    expect(gitApi.issueCredential).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('button', { name: 'Generate credentials' })).toBeInTheDocument()
  })
  it('ignores late issuance after dismissal and prevents repeated clicks while pending', async () => {
    let finish
    const gitApi = api()
    gitApi.issueCredential.mockImplementation(() => new Promise((resolve) => { finish = resolve }))
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    const generate = screen.getByRole('button', { name: 'Generate credentials' })
    fireEvent.click(generate); fireEvent.click(generate)
    await waitFor(() => expect(gitApi.issueCredential).toHaveBeenCalledTimes(1))
    fireEvent.click(screen.getByRole('button', { name: 'Close Git access' }))
    await openAccess()
    await act(async () => finish({ data: credential }))
    expect(screen.queryByText('synthetic-secret')).not.toBeInTheDocument()
  })
  it.each(['permission', 'session'])('clears issued secrets on %s loss', async (kind) => {
    const gitApi = api()
    const renderMenu = (active) => <AuthContext.Provider value={{ user: active || kind === 'permission' ? { id: 'student', status: 'ACTIVE' } : null }}><RepositoryCodeMenu repository={repository} gitApi={gitApi} available={active || kind === 'session'} canWrite /></AuthContext.Provider>
    const view = render(renderMenu(true))
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByText('synthetic-secret')
    view.rerender(renderMenu(false))
    expect(screen.queryByText('synthetic-secret')).not.toBeInTheDocument()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('clears displayed secrets after a confirmed backend denial and never claims copy success on failure', async () => {
    const gitApi = api()
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: vi.fn().mockRejectedValue(new Error('Denied')) } })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByText('synthetic-secret')
    fireEvent.click(screen.getByRole('button', { name: 'Copy token' }))
    expect(await screen.findByText('Couldn’t copy. Try again.')).toBeInTheDocument()
    gitApi.listCredentials.mockRejectedValue(new ApiError({ status: 403 }))
    fireEvent.click(screen.getByRole('button', { name: 'Manage access' }))
    await screen.findByRole('alert')
    expect(screen.queryByText('synthetic-secret')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Generate write access' })).not.toBeInTheDocument()
  })
  it('supports keyboard menu actions, a trapped modal, Escape, and focus restoration', async () => {
    const user = userEvent.setup()
    render(<RepositoryCodeMenu repository={repository} gitApi={api()} available canWrite />)
    const code = screen.getByRole('button', { name: 'Code' })
    code.focus(); await user.keyboard('{ArrowDown}')
    expect(screen.getByRole('button', { name: 'Copy URL' })).toHaveFocus()
    await user.keyboard('{ArrowDown}{Enter}')
    await screen.findByRole('dialog', { name: 'Git access' })
    const last = screen.getByRole('button', { name: 'How to use Git' })
    last.focus(); await user.tab()
    expect(screen.getByRole('button', { name: 'Close Git access' })).toHaveFocus()
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(code).toHaveFocus()
  })
  it('opens beginner help in one modal with command examples outside the dropdown', async () => {
    const gitApi = api()
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available />)
    fireEvent.click(screen.getByRole('button', { name: 'Code' }))
    fireEvent.click(screen.getByRole('button', { name: 'How to use Git' }))
    expect(screen.getByRole('dialog', { name: 'How to use Git' })).toBeInTheDocument()
    expect(screen.getAllByRole('dialog')).toHaveLength(1)
    for (const word of ['Clone once.', 'Edit.', 'Commit.', 'Pull.', 'Push.']) expect(screen.getByText(word)).toBeInTheDocument()
    expect(gitApi.issueCredential).not.toHaveBeenCalled()
    expect(gitApi.listCredentials).not.toHaveBeenCalled()
  })
  it('retries a failed permission read inside the modal without generating access', async () => {
    const gitApi = api()
    const validateAccess = vi.fn().mockRejectedValueOnce(new ApiError({ status: 503 })).mockResolvedValue({ canRead: true, canWrite: true })
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite validateAccess={validateAccess} />)
    await openAccess()
    await screen.findByRole('alert')
    expect(screen.getByRole('button', { name: 'Generate credentials' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Try again' }))
    expect(await screen.findByRole('button', { name: 'Generate credentials' })).toBeEnabled()
    expect(validateAccess).toHaveBeenCalledTimes(2)
    expect(gitApi.issueCredential).not.toHaveBeenCalled()
  })

  it.each(['missing', 'denied', 'changed'])('fails closed on %s authoritative access and never issues', async (kind) => {
    const gitApi = api()
    const denied = { data: { id: repository.id, gitPermissions: { read: false, write: false, canUpdateMain: false } } }
    if (kind === 'missing') gitApi.getAccess.mockResolvedValue({ data: { id: repository.id } })
    else if (kind === 'denied') gitApi.getAccess.mockResolvedValue(denied)
    else gitApi.getAccess.mockResolvedValueOnce({ data: { id: repository.id, gitPermissions: { read: true, write: true, canUpdateMain: false } } }).mockResolvedValue(denied)
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite />)
    await openAccess()
    if (kind === 'changed') fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByRole('alert')
    expect(gitApi.issueCredential).not.toHaveBeenCalled()
  })
  it('uses current server authority despite stale frontend write hints', async () => {
    const gitApi = api(true)
    render(<RepositoryCodeMenu repository={repository} gitApi={gitApi} available canWrite={false} />)
    await openAccess()
    fireEvent.click(screen.getByRole('button', { name: 'Generate credentials' }))
    await screen.findByText('synthetic-secret')
    expect(gitApi.issueCredential).toHaveBeenCalledExactlyOnceWith('repo', ['READ', 'WRITE'])
    expect(screen.getByText('Read and write')).toBeInTheDocument()
    expect(gitApi.getAccess).toHaveBeenCalledTimes(2)
  })

})
